CREATE TABLE IF NOT EXISTS account (
  id INTEGER PRIMARY KEY, username TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL,
  admin INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS role (
  id INTEGER PRIMARY KEY, name TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS account_role (
  account_id INTEGER NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  role_id INTEGER NOT NULL REFERENCES role(id) ON DELETE CASCADE,
  PRIMARY KEY(account_id, role_id)
);
CREATE TABLE IF NOT EXISTS skill (
  id INTEGER PRIMARY KEY, slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
  description TEXT NOT NULL, draft BLOB NOT NULL,
  revision INTEGER NOT NULL DEFAULT 1, published_revision INTEGER,
  archived INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS skill_role (
  skill_id INTEGER NOT NULL REFERENCES skill(id) ON DELETE CASCADE,
  role_id INTEGER NOT NULL REFERENCES role(id) ON DELETE CASCADE,
  PRIMARY KEY(skill_id, role_id)
);
CREATE TABLE IF NOT EXISTS release (
  skill_id INTEGER NOT NULL REFERENCES skill(id),
  version TEXT NOT NULL, major INTEGER NOT NULL, minor INTEGER NOT NULL, patch INTEGER NOT NULL,
  name TEXT NOT NULL, description TEXT NOT NULL, archive BLOB NOT NULL,
  released_at TEXT NOT NULL, PRIMARY KEY(skill_id, version)
);
CREATE TABLE IF NOT EXISTS device_token (
  id TEXT PRIMARY KEY, secret_hash TEXT NOT NULL UNIQUE,
  account_id INTEGER NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  name TEXT NOT NULL, created_at TEXT NOT NULL
);
